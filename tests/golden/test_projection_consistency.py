@pytest.mark.golden
class TestProjectionMatrixProperties:
    """Test mathematical properties of projection matrices."""
    
    def test_projection_matrix_shape(self, golden_P_laptop):
        """Projection matrix has expected shape (768, 768)."""
        assert golden_P_laptop.shape == (768, 768), (
            f"Expected shape (768, 768), got {golden_P_laptop.shape}"
        )
    
    def test_projection_matrix_dtype(self, golden_P_laptop):
        """Projection matrix is stored as FP32."""
        assert golden_P_laptop.dtype == torch.float32, (
            f"Expected dtype float32, got {golden_P_laptop.dtype}"
        )
    
    def test_projection_matrix_finite(self, golden_P_laptop):
        """Projection matrix contains no NaN or Inf values."""
        assert torch.isfinite(golden_P_laptop).all(), (
            "Projection matrix contains non-finite values"
        )
    
    def test_projection_matrix_bounded(self, golden_P_laptop):
        """Projection matrix eigenvalues are in [0, 1] (projection property)."""
        # Compute eigenvalues
        eigenvalues = torch.linalg.eigvalsh(golden_P_laptop)
        
        # Check bounds (with tolerance for numerical errors)
        assert eigenvalues.min() >= -1e-5, (
            f"Eigenvalues below 0: min={eigenvalues.min():.6f}"
        )
        assert eigenvalues.max() <= 1.0 + 1e-5, (
            f"Eigenvalues above 1: max={eigenvalues.max():.6f}"
        )
